import Foundation

/// The program behind every launcher: `Contents/MacOS/claude-launcher`, a bash
/// script that reads `INSTANCE_NAME` from the `config.sh` next to it.
///
/// On click it focuses the environment's window if there is one; if Claude is
/// running on that profile without a window it asks for a new one (it never
/// kills it: a reply may still be in progress); otherwise it starts Claude.
///
/// Claude is started from a per-environment APFS clone of Claude.app that
/// carries the launcher's icon as a Finder custom icon. That icon lives outside
/// the code seal, so Anthropic's signature stays valid, and the Dock shows the
/// running app with the launcher's look. If cloning fails, Claude.app is used.
public enum LauncherScript {
    /// Bumped whenever the text changes, so existing launchers get rewritten.
    public static let version = 5
    public static let marker = "# double-trouble-launcher \(version)"

    public static let text = #"""
#!/bin/bash
# double-trouble-launcher 5
# Generated by Double Trouble. Edit the environment from the app, not here.

here="$(cd "$(dirname "$0")" && pwd)"
. "$here/config.sh"

claude_app="/Applications/Claude.app"
profile="$HOME/.claude-instances/$INSTANCE_NAME"
slot="$HOME/Library/Application Support/Double Trouble/Clones.noindex/$INSTANCE_NAME"
copy="$slot/Claude.app"
icon="$here/../Resources/claude-icon.icns"

# One line per Claude process on this profile: "main <pid>" for the app itself,
# "window" for each renderer helper (an open window has at least one).
# Helpers live in Claude.app/Contents/Frameworks and carry --type=.
# The [.] in the patterns keeps awk from matching its own command line.
scan() {
    ps -axww -o pid=,command= | awk -v flag="--user-data-dir=$profile" -v plain="$1" '
        $0 !~ /Claude[.]app\/Contents\// { next }
        plain == "yes" && index($0, "--user-data-dir=") { next }
        plain != "yes" && !index($0 " ", flag " ") { next }
        /--type=renderer/ { print "window"; next }
        /Claude[.]app\/Contents\/MacOS\/Claude( |$)/ && !/--type=/ { print "main " $1 }'
}

# Empty when there is no such app. (PlistBuddy reports a missing file on stdout.)
version_of() {
    [ -f "$1/Contents/Info.plist" ] || return 0
    /usr/libexec/PlistBuddy -c "Print :CFBundleVersion" "$1/Contents/Info.plist" 2>/dev/null
}

# Succeeds when version $1 sorts before $2, comparing each dotted part as a number.
older() {
    [ "$1" != "$2" ] && [ "$(printf '%s\n%s\n' "$2" "$1" | sort -t. -k1,1n -k2,2n -k3,3n -k4,4n | head -n1)" = "$1" ]
}

# Makes sure $copy is a current clone of Claude.app wearing our icon.
# Only runs while nothing is using the clone.
prepare_copy() {
    local app_version copy_version
    app_version=$(version_of "$claude_app")
    copy_version=$(version_of "$copy")
    # Clone again when there is no copy, when Claude.app is newer, or when
    # Claude.app caught up with a copy that updated itself (the two versions
    # match but share no disk blocks any more).
    if [ -z "$copy_version" ] || older "$copy_version" "$app_version" \
        || { [ "$copy_version" = "$app_version" ] && [ "$(cat "$slot/.source-version" 2>/dev/null)" != "$app_version" ]; }; then
        mkdir -p "$slot" || return 1
        rm -rf "$slot/incoming.app"
        if ! /bin/cp -c -R "$claude_app" "$slot/incoming.app" 2>/dev/null; then
            rm -rf "$slot/incoming.app"
            return 1
        fi
        rm -rf "$copy" && mv "$slot/incoming.app" "$copy" || return 1
        echo "$app_version" > "$slot/.source-version"
        rm -f "$slot/.icon-applied"
    fi
    # Updates drop the custom icon, and the launcher's icon changes when it is edited.
    if [ ! -e "$copy/Icon"$'\r' ] || [ "$icon" -nt "$slot/.icon-applied" ]; then
        /usr/bin/osascript -l JavaScript -e '
            ObjC.import("AppKit");
            function run(args) {
                var picture = $.NSImage.alloc.initWithContentsOfFile(args[0]);
                return $.NSWorkspace.sharedWorkspace.setIconForFileOptions(picture, args[1], 0);
            }' "$icon" "$copy" >/dev/null 2>&1 && touch "$slot/.icon-applied"
    fi
    [ -x "$copy/Contents/MacOS/Claude" ]
}

start() {
    if [ "$INSTANCE_NAME" = "default" ]; then
        open -n -a "$1"
    else
        mkdir -p "$profile"
        open -n -a "$1" --args --user-data-dir="$profile"
    fi
}

[ "$INSTANCE_NAME" = "default" ] && plain=yes || plain=no
state="$(scan "$plain")"
pid="$(printf '%s\n' "$state" | awk '$1 == "main" { print $2; exit }')"

if [ -n "$pid" ] && printf '%s\n' "$state" | grep -qx window; then
    # Needs the one-time "control System Events" permission.
    osascript -e "tell application \"System Events\" to set frontmost of (first process whose unix id is $pid) to true" 2>/dev/null
elif [ -n "$pid" ]; then
    # Running without a window: ask the same bundle for one. Never swap the
    # clone under a running process.
    running_app="$(ps -o command= -p "$pid" | sed -E 's#\.app/Contents/MacOS/.*#.app#')"
    [ -d "$running_app" ] || running_app="$claude_app"
    start "$running_app"
elif prepare_copy; then
    start "$copy"
else
    start "$claude_app"
fi
"""#
}
